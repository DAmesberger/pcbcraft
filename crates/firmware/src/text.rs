//! Escaping shared by the emitters. Every label in the IR is user or
//! library text, so nothing reaches generated code unescaped.
use sparksmith_core::firmware::sanitise;
use sparksmith_core::functions::{Level, Pull};
use std::fmt::Write;

/// A C string literal. Bytes outside printable ASCII become three-digit
/// octal escapes, which (unlike `\x`) never absorb a following character.
pub fn c_string(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 2);
    out.push('"');
    for byte in text.bytes() {
        match byte {
            b'"' => out.push_str("\\\""),
            b'\\' => out.push_str("\\\\"),
            // `??x` trigraphs in older C dialects.
            b'?' => out.push_str("\\?"),
            0x20..=0x7e => out.push(char::from(byte)),
            _ => {
                let _ = write!(out, "\\{byte:03o}");
            }
        }
    }
    out.push('"');
    out
}

/// Text safe inside a `/* */` or `//` comment on one line: control
/// characters become spaces and `*/` is broken up.
pub fn comment(text: &str) -> String {
    text.chars()
        .map(|c| if c.is_control() { ' ' } else { c })
        .collect::<String>()
        .replace("*/", "* /")
}

/// A Rust string literal (`str`'s `Debug` form is valid Rust syntax).
pub fn rust_string(text: &str) -> String {
    format!("{text:?}")
}

/// A lower-case devicetree label or C identifier fragment.
pub fn lower_ident(text: &str) -> String {
    sanitise(text).to_ascii_lowercase()
}

pub fn pull_name(pull: Pull) -> &'static str {
    match pull {
        Pull::None => "NONE",
        Pull::Up => "UP",
        Pull::Down => "DOWN",
    }
}

pub fn level_name(level: Level) -> &'static str {
    match level {
        Level::Low => "LOW",
        Level::High => "HIGH",
    }
}

/// The comment lines every generated file starts with.
pub fn preamble(report: &sparksmith_core::firmware::PinConfigReport) -> Vec<String> {
    let device = &report.device;
    let mut lines = vec![format!(
        "Pin configuration of {} ({}), generated by {}.",
        comment(&device.designator),
        comment(&device.component_name),
        sparksmith_core::product::NAME
    )];
    if let Some(mpn) = &device.mpn {
        lines.push(format!("Part: {}.", comment(mpn)));
    }
    lines.push(
        "A starting point: pin configuration only; it configures no clocks or registers.".into(),
    );
    lines.push("Regenerate it from the design; edits here are not read back.".into());
    lines
}
