/// Most lands one mechanical part has.
pub const MAX_LANDS: usize = 64;
/// Longest land name (the pad number), bytes.
pub const MAX_LAND_NAME: usize = 16;
/// Smallest and largest land or hole size, mm.
pub const LAND_MIN_MM: f64 = 0.05;
pub const LAND_MAX_MM: f64 = 100.0;
/// Longest part name and source text, bytes.
pub const MAX_PART_NAME: usize = 128;
/// Paste windows of an annular land: this many ring segments of this sweep.
const PASTE_SEGMENTS: u32 = 4;
const PASTE_SWEEP_DEG: f64 = 70.0;
/// Vertices per arc of a paste segment.
const PASTE_ARC_STEPS: usize = 8;
/// The symbol grid, mm.
const GRID: f64 = 2.5;
const PROVENANCE: &str = "Generated by Pcbcraft from a part file (docs/mechanical-parts.md).";

/// The variant record of a component generated from a part file. Display,
/// dedupe and assembly flags only: electrical rules never read it.
#[derive(Clone, Debug, Serialize, Deserialize, JsonSchema, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct MechanicalPart {
    /// SHA-256 over the canonical JSON of the part file's asset hash, the
    /// values, the lands, the pad use and the flags ([`variant_key`]).
    pub key: ContentHash,
    /// The part's name as chosen ("SMD nut"); the component's name adds
    /// the values.
    pub name: String,
    /// What the part was chosen as: a built-in name or a file name
    /// (`*.solidcraft`).
    pub source: String,
    pub pads: PadUse,
    pub bom: bool,
    pub pick_and_place: bool,
}

/// Whether a mechanical part's copper lands land terminals.
#[derive(Clone, Copy, Debug, Default, Serialize, Deserialize, JsonSchema, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum PadUse {
    /// Mechanical copper with no terminal: no net, no ERC.
    #[default]
    Mechanical,
    /// Each copper land lands its own terminal `1…N`, which can join a net
    /// through the part's symbol on a sheet.
    Terminals,
}

/// One land of a mechanical part, in the footprint frame (mm).
#[derive(Clone, Debug, Serialize, Deserialize, JsonSchema, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct MechanicalLand {
    /// The pad number: 1–16 bytes of ASCII letters, digits, `_` and `-`.
    pub name: String,
    pub at: Point,
    pub shape: LandShape,
}

/// A land's shape.
#[derive(Clone, Debug, Serialize, Deserialize, JsonSchema, PartialEq)]
#[serde(rename_all = "snake_case", deny_unknown_fields)]
pub enum LandShape {
    /// Round copper, optionally around a non-plated hole (an annular land).
    Circle {
        diameter: f64,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        hole: Option<f64>,
    },
    Rect {
        size: Point,
        #[serde(default)]
        rotation_deg: f64,
    },
    /// A bare non-plated hole.
    Hole { diameter: f64 },
}

impl LandShape {
    /// Whether the land is copper (not a bare hole).
    pub fn copper(&self) -> bool {
        !matches!(self, Self::Hole { .. })
    }
}

/// Where a mechanical part's Model comes from.
#[derive(Clone, Debug, Serialize, Deserialize, JsonSchema, PartialEq)]
#[serde(rename_all = "snake_case", tag = "from", deny_unknown_fields)]
pub enum PartModelSource {
    /// A published Model revision of format `solidcraft`.
    Model { model: ModelRef },
    /// The part file itself: published as a new Model unless the project
    /// already has a Model of format `solidcraft` with this asset hash.
    File {
        name: String,
        definition: Box<ModelDefinition>,
        asset: PackedAsset,
    },
}

/// Everything `layout.place_part` and `layout.set_part` need to find or
/// make a mechanical part's variant.
#[derive(Clone, Debug, Serialize, Deserialize, JsonSchema, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct PartSpec {
    /// The part's name, e.g. "SMD nut".
    pub name: String,
    /// 1–8 uppercase letters (H, HS, MP, …).
    pub designator_prefix: String,
    /// A built-in name or a file name (display).
    pub source: String,
    pub model: PartModelSource,
    #[serde(default)]
    pub values: BTreeMap<String, PartValue>,
    pub derived: PartDerived,
    #[serde(default)]
    pub lands: Vec<MechanicalLand>,
    #[serde(default)]
    pub pads: PadUse,
    #[serde(default = "yes")]
    pub bom: bool,
    /// Default: whether the part has copper lands.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub pick_and_place: Option<bool>,
}

fn yes() -> bool {
    true
}

fn size_ok(v: f64) -> bool {
    v.is_finite() && (LAND_MIN_MM..=LAND_MAX_MM).contains(&v)
}

fn text_ok(text: &str, max: usize) -> bool {
    !text.trim().is_empty() && text.len() <= max && !text.chars().any(char::is_control)
}

fn invalid(message: String) -> Error {
    Error::Invalid(format!("part.spec: {message}"))
}

impl PartSpec {
    /// Whether any land is copper.
    pub fn has_copper(&self) -> bool {
        self.lands.iter().any(|l| l.shape.copper())
    }

    /// The effective pick-and-place flag.
    pub fn in_pick_and_place(&self) -> bool {
        self.pick_and_place.unwrap_or_else(|| self.has_copper())
    }

    /// Bounds and shape rules of the request (the publish rules check the
    /// generated set again).
    pub fn validate(&self) -> Result<()> {
        if !text_ok(&self.name, MAX_PART_NAME) {
            return Err(invalid(format!(
                "a part needs a printable name of 1–{MAX_PART_NAME} bytes"
            )));
        }
        if !text_ok(&self.source, MAX_LABEL) {
            return Err(invalid("a part needs its source named".into()));
        }
        if !designator_prefix_valid(&self.designator_prefix) {
            return Err(invalid(format!(
                "the designator prefix ‘{}’ is not 1–8 uppercase letters",
                self.designator_prefix.chars().take(16).collect::<String>()
            )));
        }
        if self.values.len() > super::package_model::MAX_PART_VALUES
            || !self
                .values
                .iter()
                .all(|(name, value)| part_parameter_name_ok(name) && value.finite())
        {
            return Err(invalid(
                "values are at most 256 finite literals named by part parameters".into(),
            ));
        }
        let [lo, hi] = self.derived.bounds_mm;
        if !finite_within(&lo) || !finite_within(&hi) || (0..3).any(|i| hi[i] < lo[i]) {
            return Err(invalid("the part's bounds are not a finite box".into()));
        }
        if self.derived.bodies == 0 {
            return Err(invalid("the part has no bodies".into()));
        }
        if self.lands.len() > MAX_LANDS {
            return Err(invalid(format!("a part has at most {MAX_LANDS} lands")));
        }
        let mut names = BTreeSet::new();
        for land in &self.lands {
            let name_ok = !land.name.is_empty()
                && land.name.len() <= MAX_LAND_NAME
                && land
                    .name
                    .bytes()
                    .all(|c| c.is_ascii_alphanumeric() || c == b'_' || c == b'-');
            if !name_ok {
                return Err(invalid(format!(
                    "a land name is 1–{MAX_LAND_NAME} ASCII letters, digits, ‘_’ or ‘-’"
                )));
            }
            if !names.insert(land.name.as_str()) {
                return Err(invalid(format!("two lands are named {}", land.name)));
            }
            if !finite_within(&land.at) || land.at.iter().any(|v| v.abs() > LAND_MAX_MM) {
                return Err(invalid(format!(
                    "land {} lies outside ±{LAND_MAX_MM} mm",
                    land.name
                )));
            }
            let shape_ok = match &land.shape {
                LandShape::Circle { diameter, hole } => {
                    size_ok(*diameter) && hole.is_none_or(|h| size_ok(h) && h < *diameter)
                }
                LandShape::Rect { size, rotation_deg } => {
                    size.iter().all(|v| size_ok(*v))
                        && rotation_deg.is_finite()
                        && rotation_deg.abs() <= 360.0
                }
                LandShape::Hole { diameter } => size_ok(*diameter),
            };
            if !shape_ok {
                return Err(invalid(format!(
                    "land {} needs sizes of {LAND_MIN_MM}–{LAND_MAX_MM} mm and a hole smaller than its land",
                    land.name
                )));
            }
        }
        Ok(())
    }
}

/// The variant key of `spec` for the part file `asset`.
pub fn variant_key(spec: &PartSpec, asset: ContentHash) -> Result<ContentHash> {
    #[derive(Serialize)]
    struct Canonical<'a> {
        asset: String,
        values: &'a BTreeMap<String, PartValue>,
        lands: &'a [MechanicalLand],
        pads: PadUse,
        bom: bool,
        pick_and_place: bool,
    }
    let text = serde_json::to_vec(&Canonical {
        asset: asset.to_string(),
        values: &spec.values,
        lands: &spec.lands,
        pads: spec.pads,
        bom: spec.bom,
        pick_and_place: spec.in_pick_and_place(),
    })
    .map_err(|e| Error::Invalid(format!("part.spec: {e}")))?;
    Ok(ContentHash(Sha256::digest(&text).into()))
}

/// The definitions of one variant.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct VariantRefs {
    pub component: ComponentRef,
    pub symbol: SymbolRef,
    pub binding: BindingRef,
    pub footprint: FootprintRef,
    pub package: PackageRef,
}

/// The component lineage whose latest revision is the variant `key`.
pub fn find_variant(library: &Library, key: ContentHash) -> Option<VariantRefs> {
    let ids: BTreeSet<DefinitionId> = library.components.iter().map(|c| c.id).collect();
    ids.into_iter()
        .filter_map(|id| latest_of(&library.components, id))
        .filter_map(|c| variant_refs(library, ComponentRef::new(c.id, c.revision)))
        .find(|refs| record(library, refs).is_some_and(|m| m.key == key))
}

fn record<'a>(library: &'a Library, refs: &VariantRefs) -> Option<&'a MechanicalPart> {
    library
        .package(refs.package)
        .and_then(|p| p.definition.mechanical.as_deref())
}

/// A mechanical component revision's symbol, binding, footprint and
/// package (its first of each), or `None` for any other component.
pub fn variant_refs(library: &Library, component: ComponentRef) -> Option<VariantRefs> {
    let published = library.component(component)?;
    let symbol = *published.definition.representations.first()?;
    let binding = *published.definition.implementations.first()?;
    let body = &library.binding(binding)?.definition;
    let footprint = *body.footprints.first()?;
    let refs = VariantRefs {
        component,
        symbol,
        binding,
        footprint,
        package: body.package,
    };
    record(library, &refs)?;
    Some(refs)
}

/// The mechanical record of a component revision (on its package).
pub fn mechanical_of(library: &Library, component: ComponentRef) -> Option<&MechanicalPart> {
    let refs = variant_refs(library, component)?;
    record(library, &refs)
}

/// Whether every implementation of `component` lands a mechanical-part
/// package (such a component may have no terminals).
pub fn implemented_mechanically(library: &Library, component: &ComponentDefinition) -> bool {
    !component.implementations.is_empty()
        && component.implementations.iter().all(|b| {
            library
                .binding(*b)
                .and_then(|b| library.package(b.definition.package))
                .is_some_and(|p| p.definition.mechanical.is_some())
        })
}

/// Whether instances of `component` belong in the BOM (true for every
/// component that is not a mechanical part excluded from it).
pub fn in_bom(library: &Library, component: ComponentRef) -> bool {
    mechanical_of(library, component).is_none_or(|m| m.bom)
}

/// Whether instances of `component` belong in pick-and-place.
pub fn in_pick_and_place(library: &Library, component: ComponentRef) -> bool {
    mechanical_of(library, component).is_none_or(|m| m.pick_and_place)
}

/// The Model `spec` uses: an existing revision, or a new one to publish
/// with the asset to pack.
enum ModelChoice {
    Existing(ModelRef, ContentHash),
    New(Box<ModelDefinition>, String, PackedAsset),
}

fn choose_model(library: &Library, spec: &PartSpec) -> Result<ModelChoice> {
    match &spec.model {
        PartModelSource::Model { model } => {
            let published = library.model(*model).ok_or_else(|| {
                Error::NotFound(format!("part.model: the project has no model {model}"))
            })?;
            if published.definition.format != ModelFormat::Solidcraft {
                return Err(Error::Invalid(format!(
                    "part.model: the model {model} is not a SolidCraft part file"
                )));
            }
            Ok(ModelChoice::Existing(
                *model,
                published.definition.asset.hash,
            ))
        }
        PartModelSource::File {
            name,
            definition,
            asset,
        } => {
            if definition.format != ModelFormat::Solidcraft {
                return Err(Error::Invalid(
                    "part.model: a part file is a model of format solidcraft".into(),
                ));
            }
            validate_assets(std::slice::from_ref(asset))?;
            if asset.hash != definition.asset.hash
                || asset_hash(asset.data.as_slice()) != asset.hash
                || !u64::try_from(asset.data.len()).is_ok_and(|n| n == definition.asset.bytes)
            {
                return Err(Error::Invalid(
                    "part.model: the staged file is not the asset the model names".into(),
                ));
            }
            let existing = library
                .models
                .iter()
                .filter(|m| {
                    m.definition.format == ModelFormat::Solidcraft
                        && m.definition.asset.hash == asset.hash
                })
                .max_by_key(|m| (m.id, m.revision))
                .map(|m| ModelRef::new(m.id, m.revision));
            Ok(match existing {
                Some(model) => ModelChoice::Existing(model, asset.hash),
                None => ModelChoice::New(definition.clone(), name.clone(), asset.clone()),
            })
        }
    }
}

/// Find the variant of `spec`, or generate and publish it. Returns the
/// variant and whether it was created. On error the library may be partly
/// changed: callers stage on a candidate.
pub fn make_variant(
    library: &mut Library,
    spec: &PartSpec,
    allocate: &mut dyn FnMut() -> Result<DefinitionId>,
) -> Result<(VariantRefs, bool)> {
    spec.validate()?;
    let choice = choose_model(library, spec)?;
    let hash = match &choice {
        ModelChoice::Existing(_, hash) => *hash,
        ModelChoice::New(_, _, asset) => asset.hash,
    };
    let key = variant_key(spec, hash)?;
    if let Some(found) = find_variant(library, key) {
        return Ok((found, false));
    }
    let mut scratch = Drafts::default();
    let mut ids = Vec::with_capacity(6);
    let model = match choice {
        ModelChoice::Existing(model, _) => model,
        ModelChoice::New(definition, name, asset) => {
            let id = allocate()?;
            if !library.assets.iter().any(|a| a.hash == asset.hash) {
                library.assets.push(PackedAsset {
                    hash: asset.hash,
                    media_type: asset.media_type,
                    data: AssetBytes::clone(&asset.data),
                });
            }
            let meta = DefinitionMeta {
                name,
                description: String::new(),
                provenance: format!("Part file ‘{}’.", definition.asset.file_name),
            };
            drafts::create(
                &mut scratch,
                library,
                id,
                None,
                meta,
                Definition::Model(definition),
            )?;
            ids.push(id);
            ModelRef::new(id, Revision::FIRST)
        }
    };
    let package = PackageRef::new(allocate()?, Revision::FIRST);
    let footprint = FootprintRef::new(allocate()?, Revision::FIRST);
    let binding = BindingRef::new(allocate()?, Revision::FIRST);
    let symbol = SymbolRef::new(allocate()?, Revision::FIRST);
    let component = ComponentRef::new(allocate()?, Revision::FIRST);
    let name = variant_name(spec);
    let terminal_lands: Vec<&MechanicalLand> = match spec.pads {
        PadUse::Mechanical => Vec::new(),
        PadUse::Terminals => spec.lands.iter().filter(|l| l.shape.copper()).collect(),
    };
    let count =
        u32::try_from(terminal_lands.len()).map_err(|_| invalid("too many terminals".into()))?;
    let package_body = package_definition(spec, model, count, key);
    let footprint_body = footprint_definition(spec, package, &package_body)?;
    let terminals: Vec<TerminalId> = (1..=count).map(TerminalId).collect();
    let set = [
        (
            package.id,
            format!("{name} package"),
            Definition::Package(package_body),
        ),
        (
            footprint.id,
            format!("{name} footprint"),
            Definition::Footprint(footprint_body),
        ),
        (
            binding.id,
            format!("{name} binding"),
            Definition::Binding(BindingDefinition {
                component: component.id,
                package,
                mappings: (1..=count)
                    .map(|n| TerminalMap {
                        package_terminal: PackageTerminalId(n),
                        terminal: TerminalId(n),
                    })
                    .collect(),
                footprints: vec![footprint],
                unavailable: vec![],
            }),
        ),
        (
            symbol.id,
            format!("{name} symbol"),
            Definition::Symbol(symbol_definition(component.id, &terminals)?),
        ),
        (
            component.id,
            name.clone(),
            Definition::Component(component_definition(
                spec,
                &terminal_lands,
                symbol,
                binding,
            )?),
        ),
    ];
    for (id, title, definition) in set {
        let meta = DefinitionMeta {
            name: title.chars().take(MAX_LABEL).collect(),
            description: String::new(),
            provenance: PROVENANCE.into(),
        };
        drafts::create(&mut scratch, library, id, None, meta, definition)?;
        ids.push(id);
    }
    super::publish(library, &mut scratch, &ids)?;
    Ok((
        VariantRefs {
            component,
            symbol,
            binding,
            footprint,
            package,
        },
        true,
    ))
}

/// `"SMD nut height 4 mm"`: the name and the given values.
pub fn variant_name(spec: &PartSpec) -> String {
    let mut name = spec.name.trim().to_owned();
    for (param, value) in &spec.values {
        let text = match value {
            PartValue::Mm(v) => format!("{param} {} mm", trim(*v)),
            PartValue::Deg(v) => format!("{param} {}°", trim(*v)),
            PartValue::Count(n) => format!("{param} {n}"),
            PartValue::Number(v) => format!("{param} {}", trim(*v)),
        };
        if name.len() + text.len() + 1 > MAX_LABEL {
            break;
        }
        name.push(' ');
        name.push_str(&text);
    }
    name
}

fn trim(v: f64) -> String {
    let text = format!("{v:.4}");
    let text = text.trim_end_matches('0').trim_end_matches('.');
    if text == "-0" {
        "0".into()
    } else {
        text.into()
    }
}

fn package_definition(
    spec: &PartSpec,
    model: ModelRef,
    terminals: u32,
    key: ContentHash,
) -> PackageDefinition {
    let [lo, hi] = spec.derived.bounds_mm;
    PackageDefinition {
        next_local: terminals + 1,
        terminals: (1..=terminals)
            .map(|n| PackageTerminal {
                id: PackageTerminalId(n),
                designation: n.to_string(),
            })
            .collect(),
        form: PackageForm::Generic,
        envelope: [0, 1, 2].map(|i| (hi[i] - lo[i]).max(0.01)),
        model: PackageModel::PartFile(Box::new(PartFileModel {
            model,
            values: spec.values.clone(),
            derived: spec.derived.clone(),
        })),
        mechanical: Some(Box::new(MechanicalPart {
            key,
            name: spec.name.trim().to_owned(),
            source: spec.source.clone(),
            pads: spec.pads,
            bom: spec.bom,
            pick_and_place: spec.in_pick_and_place(),
        })),
        ..PackageDefinition::default()
    }
}

/// Four ring segments of an annular land, in the pad frame.
fn ring_paste(outer: f64, inner: f64, next: &mut u32) -> Result<Vec<PasteWindow>> {
    let (ro, ri) = (outer / 2.0, inner / 2.0);
    let arc = |r: f64, from: f64, to: f64| -> Vec<Point> {
        (0..=PASTE_ARC_STEPS)
            .map(|k| {
                let t = from + (to - from) * k as f64 / PASTE_ARC_STEPS as f64;
                let a = t.to_radians();
                [r * a.cos(), r * a.sin()]
            })
            .collect()
    };
    (0..PASTE_SEGMENTS)
        .map(|k| {
            let mid = 45.0 + 90.0 * f64::from(k);
            let (a, b) = (mid - PASTE_SWEEP_DEG / 2.0, mid + PASTE_SWEEP_DEG / 2.0);
            // Inset from both rims so the window stays inside the copper.
            let inset = (ro - ri) * 0.15;
            let mut points = arc(ro - inset, a, b);
            points.extend(arc(ri + inset, b, a));
            let id = ApertureId(*next);
            *next += 1;
            Ok(PasteWindow {
                id,
                shape: ShapeNm::from_mm_rounded(&Shape::polygon(points))?,
            })
        })
        .collect()
}

fn footprint_definition(
    spec: &PartSpec,
    package_ref: PackageRef,
    package: &PackageDefinition,
) -> Result<FootprintDefinition> {
    let mut pads = Vec::with_capacity(spec.lands.len());
    let mut next_terminal = 0u32;
    let mut next_aperture = 1u32;
    for (index, land) in spec.lands.iter().enumerate() {
        let id = PadId(u32::try_from(index + 1).map_err(|_| invalid("too many lands".into()))?);
        let terminal = match (spec.pads, land.shape.copper()) {
            (PadUse::Terminals, true) => {
                next_terminal += 1;
                Some(PackageTerminalId(next_terminal))
            }
            _ => None,
        };
        let base = Pad {
            id,
            kind: PadKind::Mechanical,
            terminal,
            number: land.name.clone(),
            position: land.at,
            rotation_deg: 0.0,
            side: PadSide::Top,
            shape: PadShape::Circle { diameter: 1.0 },
            hole: None,
            mask: super::MaskRule::Inherit,
            paste: PasteRule::Inherit,
            vias: Vec::new(),
        };
        let round = |d: f64| Hole {
            shape: HoleShape::Round { diameter: d },
            plated: false,
            offset: [0.0, 0.0],
        };
        pads.push(match &land.shape {
            LandShape::Circle { diameter, hole } => Pad {
                shape: PadShape::Circle {
                    diameter: *diameter,
                },
                hole: hole.map(round),
                paste: match hole {
                    Some(h) => PasteRule::Windows(ring_paste(*diameter, *h, &mut next_aperture)?),
                    None => PasteRule::Inherit,
                },
                ..base
            },
            LandShape::Rect { size, rotation_deg } => Pad {
                shape: PadShape::Rect { size: *size },
                rotation_deg: PadShape::Rect { size: *size }.canonical_rotation(*rotation_deg),
                ..base
            },
            LandShape::Hole { diameter } => Pad {
                kind: PadKind::NonPlatedHole,
                shape: PadShape::Circle {
                    diameter: *diameter,
                },
                hole: Some(round(*diameter)),
                ..base
            },
        });
    }
    let next_local = u32::try_from(pads.len() + 1).map_err(|_| invalid("too many lands".into()))?;
    let mut footprint = FootprintDefinition {
        package: package_ref,
        next_local,
        pads,
        ..FootprintDefinition::default()
    };
    let [lo, hi] = spec.derived.bounds_mm;
    let body = Bounds {
        min: [lo[0], lo[1]],
        max: [hi[0], hi[1]],
    };
    super::templates::footprint::add_standard_graphics_over(&mut footprint, package, body)?;
    Ok(footprint)
}

/// The mechanical symbol: one unit, a body with the designator above and
/// the component name below, one pin per terminal on the left.
fn symbol_definition(
    component: DefinitionId,
    terminals: &[TerminalId],
) -> Result<SymbolDefinition> {
    let rows = terminals.len().max(1) as f64;
    let half = (GRID * ((rows + 1.0) / 2.0).ceil()).max(GRID);
    let body = Bounds {
        min: [-2.0 * GRID, -half],
        max: [2.0 * GRID, half],
    };
    let gap = 0.5;
    let top = GRID * ((rows - 1.0) / 2.0).floor();
    Ok(SymbolDefinition {
        component,
        next_local: 5,
        pin_text_height_nm: PIN_TEXT_HEIGHT,
        units: vec![Unit {
            id: UnitId(1),
            label: "A".into(),
            graphics: vec![
                graphics::body_rect(GraphicId(2), body)?,
                graphics::text(
                    GraphicId(3),
                    TextContent::Designator,
                    [0.0, body.max[1] + gap],
                    Justify {
                        h: HAlign::Center,
                        v: VAlign::Bottom,
                    },
                )?,
                graphics::text(
                    GraphicId(4),
                    TextContent::ComponentName,
                    [0.0, body.min[1] - gap],
                    Justify {
                        h: HAlign::Center,
                        v: VAlign::Top,
                    },
                )?,
            ],
            pins: terminals
                .iter()
                .enumerate()
                .map(|(k, terminal)| {
                    let y = top - GRID * k as f64;
                    let mut pin = graphics::pin_toward(*terminal, [body.min[0] - GRID, y], body)?;
                    pin.name.visible = false;
                    Ok(pin)
                })
                .collect::<Result<_>>()?,
        }],
    })
}

fn component_definition(
    spec: &PartSpec,
    lands: &[&MechanicalLand],
    symbol: SymbolRef,
    binding: BindingRef,
) -> Result<ComponentDefinition> {
    let count = u32::try_from(lands.len()).map_err(|_| invalid("too many terminals".into()))?;
    Ok(ComponentDefinition {
        // Terminals 1…N, then their fixed passive functions N+1…2N.
        next_local: 2 * count + 1,
        designator_prefix: spec.designator_prefix.clone(),
        terminals: lands
            .iter()
            .zip(1..=count)
            .map(|(land, n)| Terminal {
                id: TerminalId(n),
                name: land.name.clone(),
                class: TerminalClass::Electrical(TerminalFunctions::fixed(
                    FunctionId(count + n),
                    Direction::Passive,
                )),
            })
            .collect(),
        resources: vec![],
        constraints: vec![],
        representations: vec![symbol],
        implementations: vec![binding],
        fields: vec![],
        pin_rules: vec![],
        marking: None,
        review: None,
        generic: None,
    })
}
