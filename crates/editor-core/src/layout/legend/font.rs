#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn designator_characters_have_glyphs_inside_the_grid() {
        for c in ('0'..='9')
            .chain('A'..='Z')
            .chain('a'..='z')
            .chain("-+=.,:/()#*!?_ ".chars())
        {
            let glyph = glyph(c);
            assert!(glyph.is_some(), "{c:?}");
            for stroke in glyph.into_iter().flatten() {
                assert!(!stroke.is_empty(), "{c:?}");
                for (x, y) in stroke.iter() {
                    assert!((0.0..=GRID_WIDTH).contains(x), "{c:?}");
                    assert!((-1.0..=GRID_HEIGHT).contains(y), "{c:?}");
                }
            }
        }
        assert!(glyph('\u{2126}').is_none());
    }
}
